// Конфигурация локалей — единый источник правды для маршрутизации,
// прокси и навигационных хелперов (i18n/navigation.ts).
import { defineRouting } from "next-intl/routing";

/**
 * Порядок важен: он же задаёт порядок в переключателе языка.
 * Коды — ISO 639-1, как их ждут `<html lang>`, hreflang и Intl.
 */
export const LOCALES = ["ru", "kk", "en"] as const;
export type Locale = (typeof LOCALES)[number];

/** Подписи для переключателя — на самом языке, а не в переводе. */
export const LOCALE_LABEL: Record<Locale, string> = {
  ru: "Русский",
  kk: "Қазақша",
  en: "English",
};

/**
 * Теги BCP-47 для Intl (даты, числа, деньги). Коротких «ru»/«kk»/«en» Intl
 * не хватает: у английского от региона зависит порядок частей даты, поэтому
 * берём en-GB («11 May 2024»), а не en-US («May 11, 2024») — так порядок
 * совпадает с русским и казахским и вёрстка не разъезжается.
 */
export const LOCALE_TAG: Record<Locale, string> = {
  ru: "ru-RU",
  kk: "kk-KZ",
  en: "en-GB",
};

/** Короткие подписи для узкого переключателя на телефоне. */
export const LOCALE_SHORT_LABEL: Record<Locale, string> = {
  ru: "RU",
  kk: "ҚАЗ",
  en: "EN",
};

/**
 * Локали, открытые поисковику. Остальные отдаются с `noindex`.
 *
 * Пока переведена только витрина (главная, каталог, карточка турнира, шапка и
 * подвал), а кабинет, формы и админка на казахском и английском показывают
 * русский текст. Пускать такие страницы в индекс вредно: поисковик оценивает
 * качество по тому, что видит, а посетитель из выдачи попадает на страницу,
 * наполовину на чужом языке.
 *
 * ЧТО СДЕЛАТЬ, КОГДА ПЕРЕВОД БУДЕТ ГОТОВ: вернуть сюда "kk" и "en" — этого
 * достаточно. От одного списка зависят и мета-тег robots, и hreflang, и
 * alternates в sitemap.xml.
 *
 * Закрываем именно мета-тегом, а не Disallow в robots.txt: запрет в robots
 * запрещает СКАЧИВАТЬ страницу, но не запрещает её индексировать — адрес,
 * найденный по внешней ссылке, попадёт в выдачу пустой карточкой, и снять его
 * будет нечем, потому что noindex внутри робот прочитать не сможет.
 */
export const SEARCH_INDEXED_LOCALES: readonly Locale[] = ["ru"];

export function isSearchIndexed(locale: Locale): boolean {
  return SEARCH_INDEXED_LOCALES.includes(locale);
}

export const routing = defineRouting({
  locales: LOCALES,
  defaultLocale: "ru",

  // "as-needed": русский остаётся на прежних адресах (/tournaments), казахский
  // и английский получают префикс (/kk/tournaments, /en/tournaments).
  //
  // Это осознанный выбор в пользу уже проиндексированного сайта. При "always"
  // каждый существующий адрес стал бы редиректом на /ru/..., и накопленные
  // позиции в поиске пришлось бы набирать заново — а поисковый трафик здесь
  // основной канал (ради него каталог и открыли гостю, см. proxy.ts).
  localePrefix: "as-needed",

  // Заголовок Link: rel="alternate" hreflang для каждой локали — так Google
  // понимает, что три адреса это один документ на разных языках, а не дубли.
  //
  // Пока открыт один язык, заголовок выключен: он звал бы робота на /kk и
  // /en, которые мы тут же закрываем через noindex. Включится сам, когда в
  // SEARCH_INDEXED_LOCALES вернутся остальные языки.
  alternateLinks: SEARCH_INDEXED_LOCALES.length > 1,

  // Автоопределение языка по Accept-Language и cookie ВЫКЛЮЧЕНО намеренно.
  //
  // С ним запрос на "/" от браузера с англоязычными настройками получает
  // редирект на "/en" — включая робота Google, который ходит с
  // `Accept-Language: en`. Главная страница уехала бы из индекса на
  // англоязычную версию, а это основной канал трафика.
  //
  // Язык выбирается явно переключателем и живёт в адресе — он же и есть то,
  // чем делятся ссылкой. Если понадобится запоминать выбор между визитами,
  // включать надо вместе с проверкой, что робот при этом не редиректится.
  localeDetection: false,
});
