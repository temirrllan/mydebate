-- Выбор комитета в заявке на MUN.
--
-- На турнирах формата MUN участнику неактуален «Предпочитаемый язык» — ему
-- нужно выбрать комитет (раздел турнира: UNHRC, WHO, UNEP, …), который
-- организатор задал при создании турнира. Форма регистрации показывает одно
-- из двух полей в зависимости от формата (см. lib/actions/registrations.ts).
--
-- Колонка NULL-able и без значения по умолчанию: миграция ничего не
-- переписывает и применяется к заполненной базе без простоя. Существующие
-- заявки остаются без комитета.

ALTER TABLE "Registration" ADD COLUMN "committee" TEXT;
